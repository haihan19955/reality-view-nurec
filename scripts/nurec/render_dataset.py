"""Render the training dataset from a running NuRec gRPC renderer (one scene per container, see start_renderer.sh).

    python scripts/nurec/render_dataset.py [--out $NUREC_DATA] [--stride 2] [--nt 6]

Per scene, every STRIDE trajectory poses (10 Hz poses):
  inputs : 6 pinhole cams in a nuScenes-like rig (F, FL, FR, BL, BR, B) at 640x352, at the real cameras' mount points
  targets: NT novel viewpoints around the ego: chase cams (behind/above, lateral jitter) and orbit cams looking at the ego
  depth  : lidar rendered from a roof-mounted virtual lidar, projected (z-buffer) into every image -> sparse metric depth png16 (1/256 m)
Poses are stored relative to the ego rig at that frame (rig: x fwd, y left, z up; cameras OpenCV: x right, y down, z fwd).
Pinhole is emulated with the OpenCV-fisheye model whose radial coeffs are the tan() Taylor series (exact to <0.2% at 75 deg).
"""
import sys
import os
import time
import json
import argparse
import numpy as np
import cv2
import grpc
from scipy.spatial.transform import Rotation as R
from realityview import paths
sys.path.insert(0, paths.NUREC_PROTO)   # generated by scripts/nurec/setup_client.sh
from nre.grpc.protos import sensorsim_pb2 as ss, sensorsim_pb2_grpc as ssg, common_pb2 as cm

ap = argparse.ArgumentParser()
ap.add_argument("--out", default=paths.NUREC_DATA)
ap.add_argument("--stride", type=int, default=2)
ap.add_argument("--nt", type=int, default=6, help="novel target views per frame")
ap.add_argument("--scenes", default="")          # comma-separated scene ids; default all
ap.add_argument("--max_frames", type=int, default=0)
ap.add_argument("--port", type=int, default=46435)
args = ap.parse_args()
W, H = 640, 352
RIG = [  # name, yaw deg (left +), focal px, which real cams' mount to average
    ("F", 0, 506, ["front_wide"]), ("FL", 55, 506, ["cross_left"]), ("FR", -55, 506, ["cross_right"]),
    ("BL", 110, 506, ["rear_left"]), ("BR", -110, 506, ["rear_right"]), ("B", 180, 324, ["rear_left", "rear_right"])]
TF = 320.0   # target focal (90 deg hfov)

ch = grpc.insecure_channel(f"localhost:{args.port}", options=[("grpc.max_receive_message_length", 1 << 30), ("grpc.max_send_message_length", 1 << 30)])
st = ssg.SensorsimServiceStub(ch)
def P2M(p):
    M = np.eye(4); M[:3, :3] = R.from_quat([p.quat.x, p.quat.y, p.quat.z, p.quat.w]).as_matrix(); M[:3, 3] = [p.vec.x, p.vec.y, p.vec.z]; return M
def M2P(M):
    q = R.from_matrix(M[:3, :3]).as_quat(); return cm.Pose(vec=cm.Vec3(x=M[0, 3], y=M[1, 3], z=M[2, 3]), quat=cm.Quat(x=q[0], y=q[1], z=q[2], w=q[3]))
def cam_rot(f):
    """camera->rig rotation from a forward vector (OpenCV camera, rig z up)."""
    f = f / np.linalg.norm(f); r = np.cross(f, [0, 0, 1.0]); r /= np.linalg.norm(r); d = np.cross(f, r)
    return np.stack([r, d, f], 1)
def yaw_pitch(yaw, pitch):  # pitch > 0 looks down
    y, p = np.radians(yaw), np.radians(pitch); return np.array([np.cos(y) * np.cos(p), np.sin(y) * np.cos(p), -np.sin(p)])
def spec(f, shutter, lid):
    sp = ss.CameraSpec(logical_id=lid, resolution_h=H, resolution_w=W, shutter_type=shutter)
    sp.opencv_fisheye_param.CopyFrom(ss.OpenCVFisheyeCameraParam(principal_point_x=W / 2, principal_point_y=H / 2, focal_length_x=f, focal_length_y=f,
                                                                    radial_coeffs=[1 / 3, 2 / 15, 17 / 315, 62 / 2835], max_angle=np.radians(80)))
    return sp

def project_depth(pts_w, c2w, f):
    p = (np.linalg.inv(c2w) @ np.c_[pts_w, np.ones(len(pts_w))].T)[:3].T
    p = p[p[:, 2] > 0.5]; u = np.round(p[:, 0] / p[:, 2] * f + W / 2).astype(int); v = np.round(p[:, 1] / p[:, 2] * f + H / 2).astype(int)
    m = (u >= 0) & (u < W) & (v >= 0) & (v < H); u, v, z = u[m], v[m], p[m, 2]
    o = np.argsort(-z); D = np.zeros((H, W), np.float32); D[v[o], u[o]] = z[o]      # nearest wins (written last)
    return np.clip(D * 256, 0, 65535).astype(np.uint16)

scenes = st.get_available_scenes(cm.Empty()).scene_ids
if args.scenes: scenes = [s for s in scenes if any(k in s for k in args.scenes.split(","))]
rng = np.random.default_rng(0)
for scene in scenes:
    od = os.path.join(args.out, scene)
    if os.path.exists(f"{od}/meta.json"): print("skip", scene); continue
    os.makedirs(od, exist_ok=True)
    cams = st.get_available_cameras(ss.AvailableCamerasRequest(scene_id=scene)).available_cameras
    tr = st.get_available_trajectories(ss.AvailableTrajectoriesRequest(scene_id=scene)).available_trajectories[0].trajectory.poses
    real = {c.logical_id: (c, P2M(c.rig_to_camera)) for c in cams}         # value: camera->rig
    def mount(keys): return np.mean([T[:3, 3] for k, (c, T) in real.items() if any(s in k for s in keys)], 0)
    def nearest_id(fwd):  # appearance embedding: real camera looking most similarly
        return max(real, key=lambda k: real[k][1][:3, 2] @ (fwd / np.linalg.norm(fwd)) - (0.5 if "tele" in k else 0))
    shutter = cams[0].intrinsics.shutter_type
    rig = []
    for name, yaw, f, keys in RIG:
        T = np.eye(4); T[:3, :3] = cam_rot(yaw_pitch(yaw, 0)); T[:3, 3] = mount(keys)
        rig.append(dict(name=name, f=f, T=T, lid=nearest_id(T[:3, 2])))
    roof = np.array([0.8, 0.0, max(T[2, 3] for T in [r["T"] for r in rig]) + 0.3])
    meta = dict(scene=scene, W=W, H=H, depth_scale=256, rig=[dict(name=r["name"], f=r["f"], cx=W / 2, cy=H / 2, c2rig=r["T"].tolist(), appearance=r["lid"]) for r in rig],
                frames=[])
    idx = list(range(5, len(tr) - 5, args.stride))
    if args.max_frames: idx = idx[:args.max_frames]
    t0 = time.time(); n = 0
    for fi, k in enumerate(idx):
        t_us = int(tr[k].timestamp_us); E = P2M(tr[k].pose)
        Lr = np.eye(4); Lr[:3, 3] = roof
        lr = st.render_lidar(ss.LidarRenderRequest(scene_id=scene, lidar_config=ss.LidarSpec(lidar_type=ss.PANDAR128), frame_start_us=t_us, frame_end_us=t_us + 1,
                                                   sensor_pose=ss.PosePair(start_pose=M2P(E @ Lr), end_pose=M2P(E @ Lr))))
        pts = np.array(lr.point_xyzs, np.float32).reshape(-1, 3); pts_w = (E @ Lr @ np.c_[pts, np.ones(len(pts))].T)[:3].T
        views = [dict(kind="in", name=r["name"], f=r["f"], T=r["T"], lid=r["lid"]) for r in rig]
        for j in range(args.nt):
            if rng.random() < 0.5:   # chase
                back, up, lat = rng.uniform(3, 8), rng.uniform(1, 3.5), rng.uniform(-3, 3)
                pos = np.array([-back, lat, up]); look = np.array([rng.uniform(4, 15), lat * rng.uniform(0, 1), 0.5])
                kind = "chase"
            else:                    # orbit around the ego, looking at it
                a = rng.uniform(0, 2 * np.pi); rad = rng.uniform(5, 9); up = rng.uniform(2, 4.5)
                pos = np.array([1.4 + rad * np.cos(a), rad * np.sin(a), up]); look = np.array([1.4, 0, 0.6]); kind = "orbit"
            T = np.eye(4); T[:3, :3] = cam_rot(look - pos); T[:3, 3] = pos
            views.append(dict(kind=kind, name=f"T{j}", f=TF, T=T, lid=nearest_id(T[:3, 2])))
        fr = dict(t_us=t_us, ego2world=E.tolist(), views=[])
        for v in views:
            c2w = E @ v["T"]
            req = ss.RGBRenderRequest(scene_id=scene, resolution_h=H, resolution_w=W, camera_intrinsics=spec(v["f"], shutter, v["lid"]),
                                      frame_start_us=t_us, frame_end_us=t_us + 1, sensor_pose=ss.PosePair(start_pose=M2P(c2w), end_pose=M2P(c2w)),
                                      image_format=ss.JPEG, image_quality=93)
            jpg = st.render_rgb(req).image_bytes; n += 1
            base = f"{fi:04d}_{v['name']}"
            open(f"{od}/{base}.jpg", "wb").write(jpg)
            cv2.imwrite(f"{od}/{base}_d.png", project_depth(pts_w, c2w, v["f"]))
            fr["views"].append(dict(file=base, kind=v["kind"], name=v["name"], f=v["f"], c2rig=v["T"].tolist(), appearance=v["lid"]))
        meta["frames"].append(fr)
        if fi % 10 == 0: print(f"{scene} frame {fi}/{len(idx)}  {n / (time.time() - t0):.1f} img/s", flush=True)
    json.dump(meta, open(f"{od}/meta.json", "w"))
    print("done", scene, len(idx), "frames", f"{time.time() - t0:.0f}s", flush=True)

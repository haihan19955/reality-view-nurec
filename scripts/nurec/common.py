"""Shared helpers for talking to the NuRec gRPC renderer (see start_renderer.sh).

Conventions: rig x forward, y left, z up; cameras OpenCV (x right, y down, z forward).
Pinhole is emulated with the OpenCV-fisheye model whose radial coeffs are the tan() Taylor series
(exact to <0.2% at 75 deg).
"""
import os
import sys

import cv2
import grpc
import numpy as np
from scipy.spatial.transform import Rotation as R

from realityview import paths

sys.path.insert(0, paths.NUREC_PROTO)   # generated by scripts/nurec/setup_client.sh
from nre.grpc.protos import common_pb2 as cm, sensorsim_pb2 as ss, sensorsim_pb2_grpc as ssg  # noqa: E402

# name, yaw deg (left +), focal px at 640x352, which real cameras' mount points to average
RIG = [("F", 0, 506, ["front_wide"]), ("FL", 55, 506, ["cross_left"]), ("FR", -55, 506, ["cross_right"]),
       ("BL", 110, 506, ["rear_left"]), ("BR", -110, 506, ["rear_right"]), ("B", 180, 324, ["rear_left", "rear_right"])]
IN_W, IN_H = 640, 352


def connect(port=46435):
    ch = grpc.insecure_channel(f"localhost:{port}", options=[("grpc.max_receive_message_length", 1 << 30),
                                                             ("grpc.max_send_message_length", 1 << 30)])
    return ssg.SensorsimServiceStub(ch)


def p2m(p):
    m = np.eye(4)
    m[:3, :3] = R.from_quat([p.quat.x, p.quat.y, p.quat.z, p.quat.w]).as_matrix()
    m[:3, 3] = [p.vec.x, p.vec.y, p.vec.z]
    return m


def m2p(m):
    q = R.from_matrix(m[:3, :3]).as_quat()
    return cm.Pose(vec=cm.Vec3(x=m[0, 3], y=m[1, 3], z=m[2, 3]), quat=cm.Quat(x=q[0], y=q[1], z=q[2], w=q[3]))


def cam_rot(fwd, up=(0, 0, 1.0)):
    """camera->frame rotation for an OpenCV camera looking along fwd, no roll."""
    f = np.asarray(fwd, float) / np.linalg.norm(fwd)
    r = np.cross(f, up); r /= np.linalg.norm(r)
    return np.stack([r, np.cross(f, r), f], 1)


def look_at(pos, target, up=(0, 0, 1.0)):
    t = np.eye(4)
    t[:3, :3] = cam_rot(np.asarray(target, float) - np.asarray(pos, float), up)
    t[:3, 3] = pos
    return t


def yaw_pitch(yaw, pitch):
    """unit vector for yaw (left +) and pitch (> 0 looks down), degrees."""
    y, p = np.radians(yaw), np.radians(pitch)
    return np.array([np.cos(y) * np.cos(p), np.sin(y) * np.cos(p), -np.sin(p)])


def pinhole_spec(f, w, h, shutter, logical_id):
    sp = ss.CameraSpec(logical_id=logical_id, resolution_h=h, resolution_w=w, shutter_type=shutter)
    sp.opencv_fisheye_param.CopyFrom(ss.OpenCVFisheyeCameraParam(
        principal_point_x=w / 2, principal_point_y=h / 2, focal_length_x=f, focal_length_y=f,
        radial_coeffs=[1 / 3, 2 / 15, 17 / 315, 62 / 2835], max_angle=np.radians(80)))
    return sp


class Scene:
    """One scene of a running renderer: cameras, trajectory, the 6-camera input rig and render calls."""

    def __init__(self, st, scene_id):
        self.st, self.id = st, scene_id
        self.cams = st.get_available_cameras(ss.AvailableCamerasRequest(scene_id=scene_id)).available_cameras
        self.traj = st.get_available_trajectories(ss.AvailableTrajectoriesRequest(scene_id=scene_id)).available_trajectories[0].trajectory.poses
        self.real = {c.logical_id: p2m(c.rig_to_camera) for c in self.cams}       # camera -> rig
        self.shutter = self.cams[0].intrinsics.shutter_type
        self.rig = []
        for name, yaw, f, keys in RIG:
            t = np.eye(4); t[:3, :3] = cam_rot(yaw_pitch(yaw, 0)); t[:3, 3] = self.mount(keys)
            self.rig.append(dict(name=name, f=f, T=t, lid=self.nearest_id(t[:3, 2])))
        self.roof = np.array([0.8, 0.0, max(r["T"][2, 3] for r in self.rig) + 0.3])

    def mount(self, keys):
        return np.mean([t[:3, 3] for k, t in self.real.items() if any(s in k for s in keys)], 0)

    def nearest_id(self, fwd):
        """real camera looking most similarly (used for its appearance embedding)."""
        fwd = np.asarray(fwd, float) / np.linalg.norm(fwd)
        return max(self.real, key=lambda k: self.real[k][:3, 2] @ fwd - (0.5 if "tele" in k else 0))

    def pose(self, k):
        return int(self.traj[k].timestamp_us), p2m(self.traj[k].pose)

    def render_rgb(self, t_us, c2w, f, w, h, lid, fmt="jpg", quality=93):
        req = ss.RGBRenderRequest(scene_id=self.id, resolution_h=h, resolution_w=w, camera_intrinsics=pinhole_spec(f, w, h, self.shutter, lid),
                                  frame_start_us=t_us, frame_end_us=t_us + 1, sensor_pose=ss.PosePair(start_pose=m2p(c2w), end_pose=m2p(c2w)),
                                  image_format=ss.JPEG if fmt == "jpg" else ss.PNG, image_quality=quality)
        return self.st.render_rgb(req).image_bytes

    def lidar_world(self, t_us, ego2world):
        """roof-lidar points in world coordinates."""
        lt = np.eye(4); lt[:3, 3] = self.roof
        pose = ego2world @ lt
        lr = self.st.render_lidar(ss.LidarRenderRequest(scene_id=self.id, lidar_config=ss.LidarSpec(lidar_type=ss.PANDAR128),
                                                        frame_start_us=t_us, frame_end_us=t_us + 1,
                                                        sensor_pose=ss.PosePair(start_pose=m2p(pose), end_pose=m2p(pose))))
        pts = np.array(lr.point_xyzs, np.float32).reshape(-1, 3)
        return (pose @ np.c_[pts, np.ones(len(pts))].T)[:3].T


def available_scenes(st):
    return list(st.get_available_scenes(cm.Empty()).scene_ids)


def project_depth(pts_w, c2w, f, w, h):
    """sparse z-buffered depth image, uint16 metres * 256."""
    p = (np.linalg.inv(c2w) @ np.c_[pts_w, np.ones(len(pts_w))].T)[:3].T
    p = p[p[:, 2] > 0.5]
    u = np.round(p[:, 0] / p[:, 2] * f + w / 2).astype(int); v = np.round(p[:, 1] / p[:, 2] * f + h / 2).astype(int)
    m = (u >= 0) & (u < w) & (v >= 0) & (v < h); u, v, z = u[m], v[m], p[m, 2]
    o = np.argsort(-z); d = np.zeros((h, w), np.float32); d[v[o], u[o]] = z[o]       # nearest written last
    return np.clip(d * 256, 0, 65535).astype(np.uint16)


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if isinstance(data, bytes):
        open(path, "wb").write(data)
    else:
        cv2.imwrite(path, data)
